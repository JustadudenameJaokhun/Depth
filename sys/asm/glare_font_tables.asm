default rel

global glare_quadrant_glyph_table
global glare_braille_dot_table
global glare_get_quadrant_char
global glare_get_braille_char

section .data
align 16
glare_quadrant_glyph_table:
    db 0x20, 0x00, 0x00, 0x00
    db 0xE2, 0x96, 0x98, 0x00
    db 0xE2, 0x96, 0x9D, 0x00
    db 0xE2, 0x96, 0x80, 0x00
    db 0xE2, 0x96, 0x96, 0x00
    db 0xE2, 0x96, 0x8C, 0x00
    db 0xE2, 0x96, 0x9E, 0x00
    db 0xE2, 0x96, 0x9B, 0x00
    db 0xE2, 0x96, 0x97, 0x00
    db 0xE2, 0x96, 0x9A, 0x00
    db 0xE2, 0x96, 0x90, 0x00
    db 0xE2, 0x96, 0x9C, 0x00
    db 0xE2, 0x96, 0x84, 0x00
    db 0xE2, 0x96, 0x99, 0x00
    db 0xE2, 0x96, 0x9F, 0x00
    db 0xE2, 0x96, 0x88, 0x00

glare_braille_dot_table:
    db 0x01, 0x08
    db 0x02, 0x10
    db 0x04, 0x20
    db 0x40, 0x80

section .bss
    braille_buf resb 4

section .text

glare_get_quadrant_char:
    and edi, 0x0F
    lea rax, [glare_quadrant_glyph_table]
    shl edi, 2
    add rax, rdi
    ret

glare_get_braille_char:
    push rbp
    mov rbp, rsp
    and edi, 0xFF
    lea rax, [braille_buf]
    mov byte [rax], 0xE2
    mov ecx, edi
    shr ecx, 6
    and ecx, 0x03
    or cl, 0xA0
    mov byte [rax + 1], cl
    mov ecx, edi
    and ecx, 0x3F
    or cl, 0x80
    mov byte [rax + 2], cl
    mov byte [rax + 3], 0
    leave
    ret
